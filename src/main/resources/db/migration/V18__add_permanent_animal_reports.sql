CREATE TABLE TB_ARKIVE_RELATO_ANIMAL (
    ID_RELATO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ANIMAL NUMBER NOT NULL,
    ID_RESPONSAVEL_AUTOR NUMBER NOT NULL,
    DS_RELATO CLOB NOT NULL,
    DS_RELATO_BUSCA CLOB NOT NULL,
    DT_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_OCORRENCIA DATE,
    ST_ORIGEM_TRANSCRICAO CHAR(1) DEFAULT 'N' NOT NULL,

    CONSTRAINT PK_ARKIVE_RELATO_ANIMAL PRIMARY KEY (ID_RELATO),
    CONSTRAINT FK_ARKIVE_RELATO_ANIMAL FOREIGN KEY (ID_ANIMAL)
        REFERENCES TB_ARKIVE_ANIMAL (ID_ANIMAL),
    CONSTRAINT FK_ARKIVE_RELATO_AUTOR FOREIGN KEY (ID_RESPONSAVEL_AUTOR)
        REFERENCES TB_ARKIVE_RESPONSAVEL (ID_RESPONSAVEL),
    CONSTRAINT CK_ARKIVE_RELATO_TRANSCR CHECK (ST_ORIGEM_TRANSCRICAO IN ('S', 'N')),
    CONSTRAINT CK_ARKIVE_RELATO_OCORR CHECK (
        DT_OCORRENCIA IS NULL OR DT_OCORRENCIA = TRUNC(DT_OCORRENCIA)
    )
);

CREATE INDEX IX_ARKIVE_RELATO_ANIM_DATA
    ON TB_ARKIVE_RELATO_ANIMAL (ID_ANIMAL, DT_CRIACAO DESC, ID_RELATO DESC);

CREATE INDEX IX_ARKIVE_RELATO_AUTOR
    ON TB_ARKIVE_RELATO_ANIMAL (ID_RESPONSAVEL_AUTOR);

COMMENT ON TABLE TB_ARKIVE_RELATO_ANIMAL IS
    'Historico permanente e imutavel de relatos enviados por responsaveis sobre um animal.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.ID_RESPONSAVEL_AUTOR IS
    'Responsavel autenticado que criou o relato; o historico permanece apos o fim do vinculo.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.DS_RELATO IS
    'Texto original do relato, preservado para exibicao.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.DS_RELATO_BUSCA IS
    'Texto normalizado pelo backend para busca simples sem diferenca de caixa ou acentos.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.DT_CRIACAO IS
    'Data e hora de envio atribuida pelo backend no calendario de negocio.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.DT_OCORRENCIA IS
    'Data opcional em que o evento relatado ocorreu.';
COMMENT ON COLUMN TB_ARKIVE_RELATO_ANIMAL.ST_ORIGEM_TRANSCRICAO IS
    'S quando o cliente informa que o texto se originou de transcricao; N caso contrario.';
