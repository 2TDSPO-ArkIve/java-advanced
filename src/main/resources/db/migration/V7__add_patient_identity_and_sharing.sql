ALTER TABLE TB_ARKIVE_ANIMAL ADD (
    DS_ARKIVE_PATIENT_ID VARCHAR2(40) NULL
);

COMMENT ON COLUMN TB_ARKIVE_ANIMAL.DS_ARKIVE_PATIENT_ID IS 'Identificador publico permanente, opaco e nao autorizativo do paciente ArkIve.';

CREATE TABLE TB_ARKIVE_PATIENT_ACCESS (
    ID_PATIENT_ACCESS NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ANIMAL NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    TP_ACESSO VARCHAR2(20) NOT NULL,
    ID_CONCEDIDO_POR NUMBER NOT NULL,
    DT_CONCEDIDO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_EXPIRACAO TIMESTAMP NULL,
    ID_REVOGADO_POR NUMBER NULL,
    DT_REVOGADO TIMESTAMP NULL,

    CONSTRAINT PK_ARKIVE_PATIENT_ACCESS PRIMARY KEY (ID_PATIENT_ACCESS),
    CONSTRAINT CK_ARKIVE_PAT_ACCESS_TIPO CHECK (TP_ACESSO IN ('VETERINARIO', 'RESPONSAVEL')),
    CONSTRAINT CK_ARKIVE_PAT_ACCESS_REV CHECK (
        (DT_REVOGADO IS NULL AND ID_REVOGADO_POR IS NULL)
        OR (DT_REVOGADO IS NOT NULL AND ID_REVOGADO_POR IS NOT NULL)
    ),
    CONSTRAINT CK_ARKIVE_PAT_ACCESS_EXP CHECK (
        DT_EXPIRACAO IS NULL OR DT_EXPIRACAO > DT_CONCEDIDO
    ),
    CONSTRAINT FK_PAT_ACCESS_ANIMAL FOREIGN KEY (ID_ANIMAL)
        REFERENCES TB_ARKIVE_ANIMAL (ID_ANIMAL),
    CONSTRAINT FK_PAT_ACCESS_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PAT_ACCESS_GRANTOR FOREIGN KEY (ID_CONCEDIDO_POR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PAT_ACCESS_REVOKER FOREIGN KEY (ID_REVOGADO_POR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO)
);

CREATE INDEX IX_PAT_ACCESS_ANIMAL ON TB_ARKIVE_PATIENT_ACCESS (ID_ANIMAL);
CREATE INDEX IX_PAT_ACCESS_USUARIO ON TB_ARKIVE_PATIENT_ACCESS (ID_USUARIO, TP_ACESSO, DT_REVOGADO);

COMMENT ON TABLE TB_ARKIVE_PATIENT_ACCESS IS 'Concessoes explicitas e auditaveis de acesso de contas a pacientes.';

CREATE TABLE TB_ARKIVE_PATIENT_SHARE (
    ID_SHARE_TOKEN NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ANIMAL NUMBER NOT NULL,
    DS_TOKEN_HASH VARCHAR2(64) NOT NULL,
    ID_CRIADO_POR NUMBER NOT NULL,
    TP_CONVITE VARCHAR2(20) NOT NULL,
    DT_CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_EXPIRACAO TIMESTAMP NOT NULL,
    DT_USADO TIMESTAMP NULL,
    ID_USADO_POR NUMBER NULL,
    DT_REVOGADO TIMESTAMP NULL,
    ID_REVOGADO_POR NUMBER NULL,
    ID_ACESSO_RESULTADO NUMBER NULL,

    CONSTRAINT PK_ARKIVE_PATIENT_SHARE PRIMARY KEY (ID_SHARE_TOKEN),
    CONSTRAINT UK_ARKIVE_PAT_SHARE_HASH UNIQUE (DS_TOKEN_HASH),
    CONSTRAINT CK_ARKIVE_PAT_SHARE_TIPO CHECK (TP_CONVITE IN ('VETERINARIO', 'RESPONSAVEL')),
    CONSTRAINT CK_ARKIVE_PAT_SHARE_USED CHECK (
        (DT_USADO IS NULL AND ID_USADO_POR IS NULL)
        OR (DT_USADO IS NOT NULL AND ID_USADO_POR IS NOT NULL)
    ),
    CONSTRAINT CK_ARKIVE_PAT_SHARE_REV CHECK (
        (DT_REVOGADO IS NULL AND ID_REVOGADO_POR IS NULL)
        OR (DT_REVOGADO IS NOT NULL AND ID_REVOGADO_POR IS NOT NULL)
    ),
    CONSTRAINT CK_ARKIVE_PAT_SHARE_EXP CHECK (DT_EXPIRACAO > DT_CRIADO),
    CONSTRAINT CK_ARKIVE_PAT_SHARE_STATE CHECK (
        NOT (DT_USADO IS NOT NULL AND DT_REVOGADO IS NOT NULL)
    ),
    CONSTRAINT FK_PAT_SHARE_ANIMAL FOREIGN KEY (ID_ANIMAL)
        REFERENCES TB_ARKIVE_ANIMAL (ID_ANIMAL),
    CONSTRAINT FK_PAT_SHARE_CREATOR FOREIGN KEY (ID_CRIADO_POR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PAT_SHARE_USER FOREIGN KEY (ID_USADO_POR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PAT_SHARE_REVOKER FOREIGN KEY (ID_REVOGADO_POR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PAT_SHARE_ACCESS FOREIGN KEY (ID_ACESSO_RESULTADO)
        REFERENCES TB_ARKIVE_PATIENT_ACCESS (ID_PATIENT_ACCESS)
);

CREATE INDEX IX_PAT_SHARE_ANIMAL ON TB_ARKIVE_PATIENT_SHARE (ID_ANIMAL, DT_CRIADO);
CREATE INDEX IX_PAT_SHARE_CREATOR ON TB_ARKIVE_PATIENT_SHARE (ID_CRIADO_POR);

COMMENT ON TABLE TB_ARKIVE_PATIENT_SHARE IS 'Convites temporarios de compartilhamento; armazena somente SHA-256 do token secreto.';
