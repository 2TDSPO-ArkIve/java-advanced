CREATE TABLE TB_ARKIVE_NOTIFICACAO (
    ID_NOTIFICACAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    TP_NOTIFICACAO VARCHAR2(50) NOT NULL,
    DS_TITULO VARCHAR2(150) NOT NULL,
    DS_MENSAGEM VARCHAR2(500) NOT NULL,
    ID_ANIMAL NUMBER,
    TP_RECURSO VARCHAR2(50),
    ID_RECURSO NUMBER,
    DS_CHAVE_EVENTO VARCHAR2(150),
    DT_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_LEITURA TIMESTAMP,

    CONSTRAINT PK_ARKIVE_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT CK_ARKIVE_NOTIF_TIPO CHECK (TP_NOTIFICACAO IN ('CONSULTA_FINALIZADA')),
    CONSTRAINT CK_ARKIVE_NOTIF_RECURSO CHECK (TP_RECURSO IS NULL OR TP_RECURSO IN ('CONSULTA')),
    CONSTRAINT CK_ARKIVE_NOTIF_LEITURA CHECK (DT_LEITURA IS NULL OR DT_LEITURA >= DT_CRIACAO),
    CONSTRAINT UQ_ARKIVE_NOTIF_EVENTO UNIQUE (ID_USUARIO, DS_CHAVE_EVENTO),
    CONSTRAINT FK_ARKIVE_NOTIF_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_ARKIVE_NOTIF_ANIMAL FOREIGN KEY (ID_ANIMAL)
        REFERENCES TB_ARKIVE_ANIMAL (ID_ANIMAL)
);

CREATE INDEX IX_ARKIVE_NOTIF_USUARIO_DATA
    ON TB_ARKIVE_NOTIFICACAO (ID_USUARIO, DT_CRIACAO DESC);

CREATE INDEX IX_ARKIVE_NOTIF_USUARIO_LEITURA
    ON TB_ARKIVE_NOTIFICACAO (ID_USUARIO, DT_LEITURA);

CREATE INDEX IX_ARKIVE_NOTIF_ANIMAL
    ON TB_ARKIVE_NOTIFICACAO (ID_ANIMAL);

COMMENT ON TABLE TB_ARKIVE_NOTIFICACAO IS 'Caixa privada de notificacoes persistidas por conta de usuario.';
COMMENT ON COLUMN TB_ARKIVE_NOTIFICACAO.ID_USUARIO IS 'Conta destinataria e proprietaria da notificacao.';
COMMENT ON COLUMN TB_ARKIVE_NOTIFICACAO.DS_CHAVE_EVENTO IS 'Chave idempotente do evento, unica por usuario quando informada.';
COMMENT ON COLUMN TB_ARKIVE_NOTIFICACAO.DT_LEITURA IS 'Primeiro instante em que o destinatario marcou a notificacao como lida.';

CREATE TABLE TB_ARKIVE_USUARIO_DISPOSITIVO (
    ID_DISPOSITIVO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    DS_EXPO_PUSH_TOKEN VARCHAR2(255) NOT NULL,
    TP_PLATAFORMA VARCHAR2(20) NOT NULL,
    DS_INSTALACAO_ID VARCHAR2(100) NOT NULL,
    DT_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ULTIMO_CONTATO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ST_ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    DT_REVOGACAO TIMESTAMP,

    CONSTRAINT PK_ARKIVE_USUARIO_DISP PRIMARY KEY (ID_DISPOSITIVO),
    CONSTRAINT UQ_ARKIVE_USUARIO_DISP_TOKEN UNIQUE (DS_EXPO_PUSH_TOKEN),
    CONSTRAINT UQ_ARKIVE_USUARIO_DISP_INST UNIQUE (ID_USUARIO, DS_INSTALACAO_ID),
    CONSTRAINT CK_ARKIVE_USUARIO_DISP_PLAT CHECK (TP_PLATAFORMA IN ('ANDROID', 'IOS')),
    CONSTRAINT CK_ARKIVE_USUARIO_DISP_ATIVO CHECK (ST_ATIVO IN ('S', 'N')),
    CONSTRAINT CK_ARKIVE_USUARIO_DISP_REV CHECK (
        (ST_ATIVO = 'S' AND DT_REVOGACAO IS NULL)
        OR (ST_ATIVO = 'N' AND DT_REVOGACAO IS NOT NULL)
    ),
    CONSTRAINT FK_ARKIVE_USUARIO_DISP_USER FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO)
);

CREATE INDEX IX_ARKIVE_USUARIO_DISP_USER
    ON TB_ARKIVE_USUARIO_DISPOSITIVO (ID_USUARIO, ST_ATIVO);

COMMENT ON TABLE TB_ARKIVE_USUARIO_DISPOSITIVO IS 'Instalacoes moveis autenticadas aptas a receber Expo Push.';
COMMENT ON COLUMN TB_ARKIVE_USUARIO_DISPOSITIVO.DS_EXPO_PUSH_TOKEN IS 'Token Expo unico; nunca deve ser registrado em logs.';
COMMENT ON COLUMN TB_ARKIVE_USUARIO_DISPOSITIVO.DS_INSTALACAO_ID IS 'Identificador aleatorio gerado pela instalacao do aplicativo, nao um identificador de hardware.';
