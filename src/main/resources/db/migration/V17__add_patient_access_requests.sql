CREATE TABLE TB_ARKIVE_PATIENT_ACCESS_REQ (
    ID_ACCESS_REQUEST NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ANIMAL NUMBER NOT NULL,
    ID_USUARIO_SOLICITANTE NUMBER NOT NULL,
    ST_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    DT_SOLICITACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_USUARIO_RESOLVEDOR NUMBER,
    DT_RESOLUCAO TIMESTAMP,
    ID_PATIENT_ACCESS NUMBER,

    CONSTRAINT PK_ARKIVE_PAT_ACCESS_REQ PRIMARY KEY (ID_ACCESS_REQUEST),
    CONSTRAINT FK_ARKIVE_PAT_REQ_ANIMAL FOREIGN KEY (ID_ANIMAL)
        REFERENCES TB_ARKIVE_ANIMAL (ID_ANIMAL),
    CONSTRAINT FK_ARKIVE_PAT_REQ_SOLIC FOREIGN KEY (ID_USUARIO_SOLICITANTE)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_ARKIVE_PAT_REQ_RESOL FOREIGN KEY (ID_USUARIO_RESOLVEDOR)
        REFERENCES TB_ARKIVE_USUARIO (ID_USUARIO),
    CONSTRAINT FK_ARKIVE_PAT_REQ_ACCESS FOREIGN KEY (ID_PATIENT_ACCESS)
        REFERENCES TB_ARKIVE_PATIENT_ACCESS (ID_PATIENT_ACCESS),
    CONSTRAINT CK_ARKIVE_PAT_REQ_STATUS CHECK (
        ST_STATUS IN ('PENDING', 'APPROVED', 'REJECTED')
    ),
    CONSTRAINT CK_ARKIVE_PAT_REQ_RESOL CHECK (
        (ST_STATUS = 'PENDING'
            AND ID_USUARIO_RESOLVEDOR IS NULL
            AND DT_RESOLUCAO IS NULL
            AND ID_PATIENT_ACCESS IS NULL)
        OR (ST_STATUS = 'APPROVED'
            AND ID_USUARIO_RESOLVEDOR IS NOT NULL
            AND DT_RESOLUCAO IS NOT NULL
            AND ID_PATIENT_ACCESS IS NOT NULL)
        OR (ST_STATUS = 'REJECTED'
            AND ID_USUARIO_RESOLVEDOR IS NOT NULL
            AND DT_RESOLUCAO IS NOT NULL
            AND ID_PATIENT_ACCESS IS NULL)
    )
);

CREATE UNIQUE INDEX UQ_ARKIVE_PAT_REQ_PENDING
    ON TB_ARKIVE_PATIENT_ACCESS_REQ (
        CASE WHEN ST_STATUS = 'PENDING' THEN ID_ANIMAL END,
        CASE WHEN ST_STATUS = 'PENDING' THEN ID_USUARIO_SOLICITANTE END
    );

CREATE INDEX IX_ARKIVE_PAT_REQ_SOLIC_DATA
    ON TB_ARKIVE_PATIENT_ACCESS_REQ (ID_USUARIO_SOLICITANTE, DT_SOLICITACAO DESC);

CREATE INDEX IX_ARKIVE_PAT_REQ_ANIM_STATUS
    ON TB_ARKIVE_PATIENT_ACCESS_REQ (ID_ANIMAL, ST_STATUS);

CREATE INDEX IX_ARKIVE_PAT_REQ_STATUS_DATA
    ON TB_ARKIVE_PATIENT_ACCESS_REQ (ST_STATUS, DT_SOLICITACAO DESC);

COMMENT ON TABLE TB_ARKIVE_PATIENT_ACCESS_REQ IS
    'Solicitacoes autenticadas de acesso veterinario a um paciente, resolvidas por responsavel vigente.';
COMMENT ON COLUMN TB_ARKIVE_PATIENT_ACCESS_REQ.ID_USUARIO_SOLICITANTE IS
    'Conta VETERINARIO que solicitou acesso ao paciente identificado pelo ArkIve ID.';
COMMENT ON COLUMN TB_ARKIVE_PATIENT_ACCESS_REQ.ID_USUARIO_RESOLVEDOR IS
    'Conta RESPONSAVEL vigente que aprovou ou rejeitou a solicitacao.';
COMMENT ON COLUMN TB_ARKIVE_PATIENT_ACCESS_REQ.ID_PATIENT_ACCESS IS
    'Acesso explicito VETERINARIO criado ou reutilizado quando a solicitacao e aprovada.';

