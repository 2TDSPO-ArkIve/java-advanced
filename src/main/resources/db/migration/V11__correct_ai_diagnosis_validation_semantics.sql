UPDATE TB_ARKIVE_DIAGNOSTICO
SET ST_VALIDACAO_VET = NULL
WHERE ST_CONFIRMADO = 'N'
  AND ST_VALIDACAO_VET = 'N'
  AND DS_INSIGHT_IA IS NOT NULL
  AND PC_CONFIANCA IS NOT NULL;

COMMENT ON COLUMN TB_ARKIVE_DIAGNOSTICO.ST_VALIDACAO_VET IS
    'Avaliacao do veterinario sobre insight de IA: NULL nao avaliado, S util, N nao util.';
