ALTER TABLE TB_ARKIVE_RESPONSAVEL
    DROP CONSTRAINT CK_ARKIVE_RESP_TIPO;

UPDATE TB_ARKIVE_RESPONSAVEL
SET TP_RESPONSAVEL = 'RESPONSAVEL'
WHERE TP_RESPONSAVEL = 'TUTOR';

ALTER TABLE TB_ARKIVE_RESPONSAVEL
    ADD CONSTRAINT CK_ARKIVE_RESP_TIPO
    CHECK (TP_RESPONSAVEL IN (
        'RESPONSAVEL',
        'FUNCIONARIO_CLINICA',
        'FUNCIONARIO_ZOO',
        'ONG',
        'INSTITUICAO',
        'OUTRO'
    ));

ALTER TABLE TB_ARKIVE_RESPONSAVEL
    ADD TP_DOCUMENTO VARCHAR2(10) NULL;

ALTER TABLE TB_ARKIVE_RESPONSAVEL
    ADD CONSTRAINT CK_ARKIVE_RESP_TP_DOC
    CHECK (TP_DOCUMENTO IS NULL OR TP_DOCUMENTO IN ('CPF', 'RG'));

COMMENT ON COLUMN TB_ARKIVE_RESPONSAVEL.TP_RESPONSAVEL IS
    'Tipo do responsável: RESPONSAVEL, FUNCIONARIO_CLINICA, FUNCIONARIO_ZOO, ONG, INSTITUICAO ou OUTRO.';

COMMENT ON COLUMN TB_ARKIVE_RESPONSAVEL.TP_DOCUMENTO IS
    'Tipo do documento de identidade da pessoa responsável: CPF ou RG. NULL indica registro legado ou identificador de outra natureza.';
